"""Generate supabase/seed_demo_data.sql from app/data/transport_options.json.

    python scripts/generate_seed_sql.py
Run it again whenever you edit the JSON so PostgreSQL and the fixtures stay identical.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
doc = json.loads((ROOT / "app/data/transport_options.json").read_text(encoding="utf-8"))


def lit(v):
    if v is None:
        return "null"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return str(v)
    if isinstance(v, list):
        return "array[" + ", ".join(lit(x) for x in v) + "]::text[]" if v else "'{}'::text[]"
    return "'" + str(v).replace("'", "''") + "'"


def insert(table, cols, rows, key):
    out = []
    for r in rows:
        vals = ", ".join(lit(r.get(c)) for c in cols)
        updates = ", ".join(f"{c} = excluded.{c}" for c in cols if c != key)
        out.append(f"insert into public.{table} ({', '.join(cols)}) values ({vals})\n  on conflict ({key}) do update set {updates};")
    return "\n".join(out)


stop_cols = ["stop_id", "name", "city", "aliases", "latitude", "longitude", "data_source"]
opt_cols = ["option_id", "origin_stop_id", "destination_stop_id", "mode", "departure_at", "arrival_at", "fare_inr",
            "luggage_fee_inr", "status", "data_source", "operator", "seat_type", "ac", "reliability_score",
            "origin_lat", "origin_lng", "destination_lat", "destination_lng"]

sql = "-- GENERATED by scripts/generate_seed_sql.py - SIMULATED demo data. Do not edit by hand.\n"
sql += insert("transport_stops", stop_cols, doc["stops"], "stop_id") + "\n\n"
sql += insert("transport_options", opt_cols, doc["options"], "option_id") + "\n"
(ROOT / "supabase" / "seed_demo_data.sql").write_text(sql, encoding="utf-8")
print("wrote supabase/seed_demo_data.sql")
